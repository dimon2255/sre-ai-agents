//! Markdown scorecard rendering.

use std::fmt::Write as _;

use crate::score::{Call, Ratio, ScenarioScore, Summary};

/// Escape a value for a Markdown table cell; `a|b` labels would split the cell.
fn cell(s: &str) -> String {
    s.replace('|', "\\|")
}

fn mark(ok: bool) -> &'static str {
    if ok {
        "pass"
    } else {
        "**miss**"
    }
}

fn pct(r: &Ratio) -> String {
    r.pct()
        .map(|p| format!("{p:.0}%"))
        .unwrap_or_else(|| "n/a".to_string())
}

/// Render the full scorecard. `engine` names the reasoning tier that ran.
pub fn render_markdown(summary: &Summary, scores: &[ScenarioScore], engine: &str) -> String {
    let mut md = String::new();
    let _ = writeln!(md, "# Golden-Set Scorecard\n");
    let _ = writeln!(
        md,
        "Generated by `cargo run -p sre-evals`. Do not edit by hand. Method: \
         [ADR-023](../adr/023-golden-set-evaluation.md). Scenarios: {}. \
         Reasoning tier: {engine}.\n",
        summary.scenarios
    );
    let _ = writeln!(
        md,
        "Every scenario replays hand-authored fixture telemetry through the production \
         orchestrator and all five agents. Only the Azure query endpoint is \
         replaced. A tie at the top of the ranking is scored as a miss.\n"
    );

    let _ = writeln!(md, "## Headline\n");
    let _ = writeln!(md, "| Metric | Result | Count | What it measures |");
    let _ = writeln!(md, "|---|---|---|---|");
    let rows: Vec<(&str, String, String, &str)> = vec![
        (
            "Root-cause accuracy (top-1)",
            pct(&summary.root_cause_top1),
            format!("{} of {}", summary.root_cause_top1.hits, summary.root_cause_top1.total),
            "The report leads with the true root cause.",
        ),
        (
            "Root cause found at any rank",
            pct(&summary.root_cause_detected),
            format!(
                "{} of {}",
                summary.root_cause_detected.hits, summary.root_cause_detected.total
            ),
            "The cause is among the detections, even if ranked below a symptom. Excludes scenarios with no root cause.",
        ),
        (
            "Ambiguous root-cause calls",
            String::new(),
            summary.root_cause_ambiguous.to_string(),
            "Two or more categories tie at the top; arrival order decides what a reader sees.",
        ),
        (
            "Signal detection precision",
            pct(&summary.detection_precision),
            format!(
                "{} of {}",
                summary.detection_precision.hits, summary.detection_precision.total
            ),
            "Detections that correspond to a real signal.",
        ),
        (
            "Signal detection recall",
            pct(&summary.detection_recall),
            format!(
                "{} of {}",
                summary.detection_recall.hits, summary.detection_recall.total
            ),
            "Real signals that were detected.",
        ),
        (
            "Escalation accuracy",
            pct(&summary.escalation),
            format!("{} of {}", summary.escalation.hits, summary.escalation.total),
            "Paged a human exactly when the evidence did not support a confident conclusion.",
        ),
        (
            "Missed pages",
            String::new(),
            summary.missed_pages.to_string(),
            "Should have escalated and did not. The safety-critical error.",
        ),
        (
            "Unnecessary pages",
            String::new(),
            summary.unnecessary_pages.to_string(),
            "Escalated when the automation had a confident, correct-shaped answer.",
        ),
        (
            "First-choice remediation accuracy",
            pct(&summary.remediation),
            format!("{} of {}", summary.remediation.hits, summary.remediation.total),
            "The most confident proposal is an action an SRE would accept.",
        ),
        (
            "Unwarranted automated actions",
            String::new(),
            summary.unwarranted_actions.to_string(),
            "An action was proposed where no automated action fits.",
        ),
        (
            "Scenarios passing every check",
            pct(&summary.all_checks),
            format!("{} of {}", summary.all_checks.hits, summary.all_checks.total),
            "Root cause, signals, escalation and remediation all correct.",
        ),
    ];
    for (name, result, count, what) in rows {
        let _ = writeln!(md, "| {name} | {result} | {count} | {what} |");
    }
    if let Some(rca) = &summary.rca_correct {
        let _ = writeln!(
            md,
            "| LLM root-cause analysis judged correct | {} | {} of {} | An LLM judge agrees the RCA names the labeled root cause. |",
            pct(rca),
            rca.hits,
            rca.total
        );
        let _ = writeln!(
            md,
            "| LLM tier calls that failed | | {} | API or parse failures; excluded from the row above, not counted as wrong. |",
            summary.rca_errors
        );
    }
    let _ = writeln!(
        md,
        "\nMean investigation time per scenario: {:.0} ms (local fixtures, so this excludes Azure query latency).\n",
        summary.mean_duration_ms
    );

    let _ = writeln!(md, "## Per scenario\n");
    let _ = writeln!(
        md,
        "| ID | Incident | Expected root cause | Report leads with | Root cause | Signals | Escalation (expected / actual) | Remediation (accepted / proposed first) |"
    );
    let _ = writeln!(md, "|---|---|---|---|---|---|---|---|");
    for s in scores {
        let _ = writeln!(
            md,
            "| {} | {} | `{}` | `{}` | {} | {} | {} / {} {} | {} / `{}` {} |",
            s.id,
            cell(&s.title),
            cell(&s.expected_root_cause),
            cell(&s.predicted_root_cause.display()),
            mark(s.root_cause_correct),
            mark(s.signals_correct()),
            yes_no(s.expected_escalate),
            yes_no(s.escalated),
            mark(s.escalation_correct()),
            s.expected_remediation.join(", "),
            cell(&s.first_action.display()),
            mark(s.remediation_correct),
        );
    }

    let _ = writeln!(md, "\n## Signal detection by category\n");
    let _ = writeln!(
        md,
        "A finding counts as a detection when it is not informational and is Medium severity or above.\n"
    );
    let _ = writeln!(
        md,
        "| Category | Detected (TP) | False alarms (FP) | Missed (FN) | Precision | Recall |"
    );
    let _ = writeln!(md, "|---|---|---|---|---|---|");
    for (category, c) in &summary.per_category {
        let p = Ratio {
            hits: c.tp,
            total: c.tp + c.fp,
        };
        let r = Ratio {
            hits: c.tp,
            total: c.tp + c.fn_,
        };
        let _ = writeln!(
            md,
            "| `{category}` | {} | {} | {} | {} | {} |",
            c.tp,
            c.fp,
            c.fn_,
            pct(&p),
            pct(&r)
        );
    }

    let misses: Vec<&ScenarioScore> = scores.iter().filter(|s| !s.all_checks_pass()).collect();
    if !misses.is_empty() {
        let _ = writeln!(md, "\n## Misses in detail\n");
        for s in misses {
            let _ = writeln!(md, "### {} — {}\n", s.id, s.title);
            if !s.root_cause_correct {
                let tied = matches!(s.predicted_root_cause, Call::Tied(_));
                let found = match s.root_cause_detected {
                    Some(true) if tied => {
                        " The true cause was detected but tied at the top with another category, so agent arrival order decides which one a reader sees first."
                    }
                    Some(true) => " The true cause was detected but ranked below another category.",
                    Some(false) => " The true cause was not detected at all.",
                    None => "",
                };
                let _ = writeln!(
                    md,
                    "- Root cause: expected `{}`, report leads with `{}`.{found}",
                    s.expected_root_cause,
                    s.predicted_root_cause.display()
                );
            }
            if !s.signal_fn.is_empty() {
                let _ = writeln!(md, "- Signals missed: `{}`", s.signal_fn.join("`, `"));
            }
            if !s.signal_fp.is_empty() {
                let _ = writeln!(
                    md,
                    "- Signals reported that are not present: `{}`",
                    s.signal_fp.join("`, `")
                );
            }
            if !s.escalation_correct() {
                let kind = if s.expected_escalate {
                    "missed page"
                } else {
                    "unnecessary page"
                };
                let _ = writeln!(
                    md,
                    "- Escalation: expected {}, actual {} ({kind}).",
                    yes_no(s.expected_escalate),
                    yes_no(s.escalated)
                );
            }
            if !s.remediation_correct {
                let _ = writeln!(
                    md,
                    "- Remediation: accepted `{}`, first proposal `{}`.",
                    s.expected_remediation.join("`, `"),
                    s.first_action.display()
                );
                let all: Vec<String> = s
                    .proposals
                    .iter()
                    .map(|p| format!("`{}` ({:.2})", p.action, p.confidence))
                    .collect();
                let all = if all.is_empty() {
                    "none".to_string()
                } else {
                    all.join(", ")
                };
                let _ = writeln!(md, "- All proposals, most confident first: {all}.");
            }
            if let Some(rca) = &s.rca {
                let _ = writeln!(
                    md,
                    "- LLM RCA ({}): {} — \"{}\". Judge: {}",
                    rca.engine, rca.verdict, rca.root_cause, rca.judge_reason
                );
            }
            let _ = writeln!(
                md,
                "\n| Severity | Category | Confidence | Agent | Finding |"
            );
            let _ = writeln!(md, "|---|---|---|---|---|");
            for f in &s.findings {
                let _ = writeln!(
                    md,
                    "| {} | `{}` | {:.2} | {} | {} |",
                    f.severity,
                    f.category,
                    f.confidence,
                    f.agent,
                    cell(&f.title)
                );
            }
            let _ = writeln!(md);
        }
    }

    let gaps: Vec<&ScenarioScore> = scores
        .iter()
        .filter(|s| !s.unqueried_fixtures.is_empty())
        .collect();
    if !gaps.is_empty() {
        let _ = writeln!(md, "## Coverage gaps\n");
        let _ = writeln!(
            md,
            "Fixture telemetry that no agent queried. Where that telemetry holds a labeled signal, the pipeline could not have found it.\n"
        );
        let _ = writeln!(md, "| Scenario | Templates never queried |");
        let _ = writeln!(md, "|---|---|");
        for s in gaps {
            let _ = writeln!(md, "| {} | `{}` |", s.id, s.unqueried_fixtures.join("`, `"));
        }
    }
    md
}

fn yes_no(b: bool) -> &'static str {
    if b {
        "yes"
    } else {
        "no"
    }
}
